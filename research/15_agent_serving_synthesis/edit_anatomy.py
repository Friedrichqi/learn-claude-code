#!/usr/bin/env python3
"""What a harness edit throws away, message by message (offline) -- research/15_agent_serving_synthesis.

For every lead call in 11's captures whose message list is not an append-only extension of the previous lead
call's (a harness edit: compaction replaced old tool results with placeholders), compare the two lists from the
first differing message on:

  removed     old-suffix messages whose content no longer appears in the new prompt (the compacted tool results):
              their KV is gone under any policy;
  surviving   old-suffix messages whose exact content is still in the new prompt, now at shifted positions: prefix
              caching recomputes them, a position-shifted reuse (research/10, I3 / I16) would keep them;
  reply       the previous call's response, which the next prompt re-renders.

Tokens are characters / 4.61 (11 §2.2). Lead calls only.

    python research/15_agent_serving_synthesis/edit_anatomy.py [--cells n08,s3gate16] [--root DIR]
        [--out research/15_agent_serving_synthesis/data/tables/edit_anatomy.md]
"""
from __future__ import annotations

import argparse
import json
import lzma
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # research/
import _paths  # noqa: E402,F401

HERE = Path(__file__).resolve().parent
REPO = Path(__file__).resolve().parents[2]
ROOT11 = REPO / "research/11_multiuser_kv/data/multiuser_live/cells"
CPT = 4.61


def text_of(content) -> str:
    if isinstance(content, str):
        return content
    out = []
    for b in content or []:
        if not isinstance(b, dict):
            continue
        t = b.get("type")
        if t == "text":
            out.append(b.get("text", ""))
        elif t == "tool_use":
            out.append(json.dumps(b.get("input", {}), sort_keys=True))
        elif t == "tool_result":
            c = b.get("content")
            out.append(c if isinstance(c, str) else "\n".join(x.get("text", "") for x in c or [] if isinstance(x, dict)))
    return "\n".join(out)


def analyze_cell(cell: str, root: Path) -> dict | None:
    rows = []
    calls = 0
    for cap in sorted((root / cell / "runs").glob("*/*.requests.jsonl.xz")):
        reqs = []
        with lzma.open(cap, "rt") as f:
            for line in f:
                r = json.loads(line)
                if r.get("purpose") == "lead":
                    reqs.append(r)
        calls += max(0, len(reqs) - 1)
        for prev, cur in zip(reqs, reqs[1:]):
            mp = [text_of(m.get("content")) for m in prev.get("messages") or []]
            mc = [text_of(m.get("content")) for m in cur.get("messages") or []]
            k = 0
            while k < min(len(mp), len(mc)) and mp[k] == mc[k]:
                k += 1
            if k >= len(mp):
                continue                                   # append-only
            new = set(mc[k:])
            removed = sum(len(t) for t in mp[k:] if t not in new)
            surviving = sum(len(t) for t in mp[k:] if t in new)
            resp = prev.get("response") or {}
            reply = len(text_of(resp.get("content"))) if isinstance(resp, dict) else 0
            rows.append((removed / CPT, surviving / CPT, reply / CPT))
    if not rows:
        return None
    n = len(rows)
    tot = [sum(r[i] for r in rows) for i in range(3)]
    allt = sum(tot) or 1.0
    return {"cell": cell, "follow_up_calls": calls, "edits": n,
            "removed_mean": tot[0] / n, "surviving_mean": tot[1] / n, "reply_mean": tot[2] / n,
            "removed_med": statistics.median(r[0] for r in rows), "surviving_med": statistics.median(r[1] for r in rows),
            "removed_pct": 100 * tot[0] / allt, "surviving_pct": 100 * tot[1] / allt, "reply_pct": 100 * tot[2] / allt}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--cells", default="n08,s3gate16")
    ap.add_argument("--root", default=str(ROOT11))
    ap.add_argument("--out", default=str(HERE / "data/tables/edit_anatomy.md"))
    args = ap.parse_args()
    lines = ["# What a harness edit throws away (11's captures, offline)", "",
             "Generated by `research/15_agent_serving_synthesis/edit_anatomy.py`; definitions in its docstring.", "",
             "| cell | lead follow-up calls | edits | removed, tokens per edit (mean / median) | surviving at shifted positions "
             "(mean / median) | previous reply (mean) | removed / surviving / reply, % of what the edit discards |",
             "|---|---:|---:|---|---|---:|---|"]
    for cell in [c for c in args.cells.split(",") if c]:
        r = analyze_cell(cell, Path(args.root))
        if r is None:
            print(f"{cell}: no edits", file=sys.stderr)
            continue
        line = (f"| {cell} | {r['follow_up_calls']:,} | {r['edits']:,} | {r['removed_mean']:,.0f} / {r['removed_med']:,.0f} | "
                f"{r['surviving_mean']:,.0f} / {r['surviving_med']:,.0f} | {r['reply_mean']:,.0f} | "
                f"{r['removed_pct']:.0f} / {r['surviving_pct']:.0f} / {r['reply_pct']:.0f} |")
        print(line, file=sys.stderr)
        lines.append(line)
    lines += ["", "*Key.* What prefix caching discards at an edit = the previous prompt from the first changed message on, "
              "plus the previous reply. **removed**: content the new prompt no longer has (compacted tool results), gone "
              "under any policy. **surviving**: content the new prompt still has, at new positions; freeing it means "
              "recomputing it, a position-shifted reuse keeps it.", ""]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
